"""Subset the game's own fonts (assets/fonts/Orbitron.ttf and Nunito.ttf, SIL OFL 1.1, variable weight axis kept) to the
characters the compositions use, as WOFF2, plus assets/fonts/fonts.css. Re-run after changing on-screen text.

    python3 fonts.py      (needs fonttools and brotli: pip install fonttools brotli)
"""
import pathlib
import re

from fontTools import subset

here = pathlib.Path(__file__).parent
repo = here.parents[2]
out = here / 'assets' / 'fonts'
FONTS = [('Orbitron', 'Orbitron.ttf', 'orbitron', '400 900'), ('Nunito', 'Nunito.ttf', 'nunito', '200 1000')]


def used_text():
    chars = set(chr(c) for c in range(0x20, 0x7f))
    for p in [here / 'landscape' / 'index.html', here / 'portrait' / 'index.html', *(here / 'assets').glob('*.js')]:
        src = re.sub(r'<script[^>]*src=[^>]*></script>', '', p.read_text(encoding='utf-8'))
        chars |= {c for c in src if ord(c) > 0x7f and not c.isspace()}
    return ''.join(sorted(chars | set('·…’—–')))


if __name__ == '__main__':
    out.mkdir(parents=True, exist_ok=True)
    text = used_text()
    css = ['/* Generated by fonts.py: subsets of the game\'s own fonts (SIL OFL 1.1). */']
    for family, src, stem, weights in FONTS:
        opts = subset.Options()
        opts.flavor = 'woff2'
        opts.layout_features = ['*']
        opts.name_IDs = ['*']
        font = subset.load_font(str(repo / 'assets' / 'fonts' / src), opts)
        s = subset.Subsetter(opts)
        s.populate(text=text)
        s.subset(font)
        subset.save_font(font, str(out / f'{stem}.woff2'), opts)
        css.append(f"@font-face {{ font-family: '{family}'; font-weight: {weights}; font-style: normal; font-display: block; "
                   f"src: url('{stem}.woff2') format('woff2'); }}")
        print(f'{stem}.woff2: {(out / f"{stem}.woff2").stat().st_size // 1024} KB')
    (out / 'fonts.css').write_text('\n'.join(css) + '\n')
    print(f'{len(text)} characters')
